#!/usr/bin/env python3
# Generate rtl/pc6001_intfont.svh: the MC6847's built-in 64-character font (12 lines each), taken from
# CSCP src/vm/mc6847.cpp (intfont[], "from mess m6847.c").
#   python3 tools/gen_intfont.py ../common_source_code/src/vm/mc6847.cpp > rtl/pc6001_intfont.svh
import re, sys
src = open(sys.argv[1], encoding='utf-8', errors='replace').read()
i = src.index('intfont[64 * 12]')
body = src[src.index('{', i):src.index('};', i)]
vals = [int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{2})', body)]
assert len(vals) == 768, len(vals)
print('// Generated by tools/gen_intfont.py from CSCP src/vm/mc6847.cpp (intfont, from MESS m6847.c). Do not edit.')
print('function automatic [7:0] intfont(input [5:0] ch, input [3:0] line);')
print('\tcase ({ch, line})')
for n, v in enumerate(vals):
    c, l = divmod(n, 12)
    if v:
        print(f"\t\t{{6'd{c}, 4'd{l}}}: intfont = 8'h{v:02x};")
print("\t\tdefault: intfont = 8'h00;")
print('\tendcase')
print('endfunction')

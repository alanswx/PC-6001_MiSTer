#!/usr/bin/env python3
# Generate rtl/pc6001_keytable.svh from PC6001VX's P6MxCode table (src/keyboard.cpp, LGPL-2.1):
# the key code the sub CPU sends for matrix position Y (0-9), X (0-7) in each of the 8 shift groups
# (STD, SHIFT, GRAPH, KANA, KANA+SHIFT, KKANA, KKANA+SHIFT, CTRL).
#   python3 tools/gen_keytable.py refs/emulators/PC6001VX/src/keyboard.cpp > rtl/pc6001_keytable.svh
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
start = src.index('P6MxCode =')
body = src[start:src.index('};', start)]
rows = [[int(v, 16) for v in re.findall(r'0x([0-9a-fA-F]{2})', m)]
        for m in re.findall(r'\{\s*(0x[^}]*)\}', body)]
rows = [r for r in rows if len(r) == 8]
assert len(rows) >= 80, len(rows)
print('// Generated by tools/gen_keytable.py from PC6001VX src/keyboard.cpp (P6MxCode, LGPL-2.1). Do not edit.')
print('// key_code(y, x, group): group 0 STD 1 SHIFT 2 GRAPH 3 KANA 4 KANA+S 5 KKANA 6 KKANA+S 7 CTRL')
print('function automatic [7:0] key_code(input [3:0] y, input [2:0] x, input [2:0] g);')
print('\tcase ({y, x, g})')
for i, r in enumerate(rows[:80]):
    y, x = divmod(i, 8)
    for g, v in enumerate(r):
        if v:
            print(f"\t\t{{4'd{y}, 3'd{x}, 3'd{g}}}: key_code = 8'h{v:02x};")
print("\t\tdefault: key_code = 8'h00;")
print('\tendcase')
print('endfunction')
